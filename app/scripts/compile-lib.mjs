// Pure helpers for the optional LLM rule compiler (no network). Unit-tested.
const BINS = ['recycling', 'compost', 'garbage', 'special', 'reuse'];
const CONDITIONS = ['empty', 'clean', 'dry', 'flatten', 'lid-on', 'lid-off', 'caps-on', 'remove-liner', 'ball-up', 'min-3in', 'bag-shredded', 'bagged-tied', 'labeled-compostable'];

export const norm = (s) => s.replace(/\u00a0/g, ' ').replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/\s+/g, ' ').trim();

/** JSON schema the model must follow (structured outputs: every object closed, all fields required). */
export function draftSchema(itemIds) {
  return {
    type: 'object',
    additionalProperties: false,
    required: ['rules'],
    properties: {
      rules: {
        type: 'array',
        items: {
          type: 'object',
          additionalProperties: false,
          required: ['itemId', 'bin', 'prep', 'conditions', 'quote', 'section'],
          properties: {
            itemId: { type: 'string', enum: itemIds },
            bin: { type: 'string', enum: BINS },
            prep: { type: 'array', items: { type: 'string' } },
            conditions: { type: 'array', items: { type: 'string', enum: CONDITIONS } },
            quote: { type: 'string', description: 'Verbatim excerpt from the guide that justifies the bin (copy exactly).' },
            section: { type: 'string', description: 'Heading or list name in the guide where the quote appears.' },
          },
        },
      },
    },
  };
}

export function buildPrompt(cityName, guideText, catalog) {
  const list = catalog.items.map((i) => `${i.id}: ${i.name} (also: ${i.synonyms.join(', ')})`).join('\n');
  return [
    `You are compiling the official household waste-sorting guide for ${cityName} into structured rules.`,
    'Only use what the guide text below says. For each catalog item that the guide clearly covers, output one rule:',
    '- bin: recycling, compost (organics / green bin), garbage (landfill), special (drop-off, hazardous waste, deposit return, take-back) or reuse (donate).',
    '- quote: copy the shortest exact passage from the guide that justifies the bin. Do not paraphrase; it is checked character-for-character.',
    '- prep and conditions: only steps the guide states (e.g. "flatten", "remove lid", "must be empty").',
    'Skip items the guide does not mention. Never guess from general knowledge.',
    '',
    '<catalog>', list, '</catalog>',
    '',
    '<guide>', guideText, '</guide>',
  ].join('\n');
}

/**
 * Turn raw model output into a ruleset. Rules whose quote is not found verbatim in the
 * guide are dropped. Every kept rule is marked unverified until a human reviews it.
 */
export function buildDraftRuleset({ cityId, cityName, region = '', authority = '', url, guideText, llmRules, catalog, retrieved }) {
  const hay = norm(guideText);
  const ids = new Set(catalog.items.map((i) => i.id));
  const kept = [];
  const dropped = [];
  const seen = new Set();
  for (const r of llmRules) {
    const quote = norm(r.quote ?? '');
    const why = !ids.has(r.itemId) ? 'unknown item'
      : seen.has(r.itemId) ? 'duplicate item'
      : !BINS.includes(r.bin) ? 'invalid bin'
      : quote.length < 6 ? 'quote too short'
      : !hay.includes(quote) ? 'quote not found verbatim in guide'
      : null;
    if (why) { dropped.push({ itemId: r.itemId, reason: why }); continue; }
    seen.add(r.itemId);
    const rule = {
      itemId: r.itemId,
      bin: r.bin,
      citation: { sourceId: 'guide', url, section: (r.section || 'Guide').slice(0, 200), quote: quote.slice(0, 600) },
      verified: false,
      note: 'Drafted by an LLM from the pasted guide. The quote was checked verbatim; the bin mapping still needs human review.',
    };
    const prep = (r.prep ?? []).filter((p) => typeof p === 'string' && p.trim());
    const conditions = [...new Set((r.conditions ?? []).filter((c) => CONDITIONS.includes(c)))];
    if (prep.length) rule.prep = prep;
    if (conditions.length) rule.conditions = conditions;
    kept.push(rule);
  }
  const label = (l, s) => ({ label: l, short: s });
  const ruleset = {
    $schema: './ruleset.schema.json',
    schemaVersion: 1,
    city: { id: cityId, name: cityName, region, authority: authority || `${cityName} (official guide)` },
    bins: {
      recycling: label('Recycling', 'Recycle'), compost: label('Compost / organics', 'Compost'), garbage: label('Garbage', 'Garbage'),
      special: label('Drop-off or special handling', 'Special'), reuse: label('Reuse or donate', 'Reuse'),
    },
    retrieved,
    sources: [{ id: 'guide', title: `${cityName} official sorting guide`, url, publisher: authority || cityName, retrieved }],
    notes: ['Draft generated by scripts/compile-rules-llm.mjs. Review every rule before merging.'],
    general: [],
    rules: kept,
  };
  return { ruleset, dropped };
}
